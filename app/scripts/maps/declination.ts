/* THE COMPASS'S DECLINATION TABLE (Map 5c) — computed OFFLINE, here, at dev
   time, from the World Magnetic Model 2025–2030 (the `magvar` package, a
   devDependency: the app never carries the model, only this table).

   Run: npx tsx scripts/maps/declination.ts   (no network)
   Writes src/lib/logic/declination-grid.ts.

   WHY A TABLE. The phone's `deviceorientationabsolute` measures from MAGNETIC
   north; the map and every bearing the app computes are TRUE north. The
   difference is 7.6° W in Beijing and 1.4° W in Lijiang — enough to point a
   walker down the wrong lane at the end of a 2 km straight line. The model
   itself is 90 spherical-harmonic coefficients and a page of maths; a table
   of its answers, looked up with a bilinear blend, is a few KB and exact to a
   tenth of a degree where it matters.

   THE GRID: every 5° of latitude from 60° S to 75° N and every 5° of
   longitude round the world, in tenths of a degree (east positive), at one
   epoch — mid-trip, EPOCH below (the field drifts ~0.1°/year, so a table for
   the trip's own months is the honest one; regenerate for a later trip or
   when WMM2030 is published). The script checks the blend against the model
   at every stop of every seed and fails past 0.3°; `declination.test.ts`
   checks it again. */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { magvar } from 'magvar';
import type { AppBackup } from '../../src/lib/model/types';

export const EPOCH = 2026.9; // late November 2026 — the China trip
export const STEP = 5;
export const LAT0 = -60;
export const LAT1 = 75;
export const LNG0 = -180;
export const LNG1 = 180;

/** The model's answer, in degrees, east positive. */
export const wmm = (lat: number, lng: number): number => magvar(lat, lng, 0, EPOCH);

export function grid(): number[] {
  const out: number[] = [];
  for (let lat = LAT0; lat <= LAT1; lat += STEP) {
    for (let lng = LNG0; lng <= LNG1; lng += STEP) out.push(Math.round(wmm(lat, lng) * 10));
  }
  return out;
}

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, '..', '..');
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const values = grid();
  const rows = (LAT1 - LAT0) / STEP + 1;
  const cols = (LNG1 - LNG0) / STEP + 1;
  const body = values.join(',');
  const file = `/* GENERATED by scripts/maps/declination.ts — do not edit by hand.
   Magnetic declination (tenths of a degree, east positive) from the World
   Magnetic Model 2025 at epoch ${EPOCH}, every ${STEP}° from ${LAT0}° to ${LAT1}° of latitude
   (${rows} rows) and ${LNG0}° to ${LNG1}° of longitude (${cols} columns), row by row
   from the south. Looked up by lib/logic/declination.ts. */
export const EPOCH = ${EPOCH};
export const STEP = ${STEP};
export const LAT0 = ${LAT0};
export const LAT1 = ${LAT1};
export const LNG0 = ${LNG0};
export const COLS = ${cols};
export const TENTHS = '${body}';
`;
  writeFileSync(join(app, 'src', 'lib', 'logic', 'declination-grid.ts'), file);
  console.log(`declination grid: ${rows} × ${cols} = ${values.length} values, ${file.length} bytes`);

  /* the check: the blend against the model at every stop of every seed */
  const { declinationAt } = await import('../../src/lib/logic/declination');
  let worst = 0;
  for (const seedFile of ['china-2026.trip.json', 'israel-test.trip.json', 'template-example.trip.json']) {
    let seed: AppBackup;
    try {
      seed = JSON.parse(readFileSync(join(app, '..', 'seed', seedFile), 'utf8')) as AppBackup;
    } catch {
      continue;
    }
    for (const t of seed.trips) {
      for (const s of t.stops) {
        if (!s.coord) continue;
        const want = wmm(s.coord.lat, s.coord.lng);
        const got = declinationAt(s.coord.lat, s.coord.lng);
        worst = Math.max(worst, Math.abs(got - want));
        console.log(`  ${s.name.slice(0, 34).padEnd(34)} model ${want.toFixed(2).padStart(6)}°  table ${got.toFixed(2).padStart(6)}°`);
      }
    }
  }
  console.log(`worst difference at a stop: ${worst.toFixed(3)}°`);
  if (worst > 0.3) {
    console.error('The table is off by more than 0.3° at a stop — use a finer STEP.');
    process.exit(1);
  }
}

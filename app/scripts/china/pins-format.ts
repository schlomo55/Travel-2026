/* The shape of china/pins.ts, and the one function that writes it.

   pins.ts is GENERATED by `PLACES_PINS=1 npm run verify:places` from the
   cached answers, so the table the seed build reads and the evidence behind
   every entry are the same file and can never drift apart. The renderer is
   deterministic — the same answers give the same bytes — so a re-run over an
   unchanged cache leaves git with nothing to show. */
import type { Coord } from '../../src/lib/model/types';
import type { PinKind, PinSources } from './pin-rules';

/** One place the coordinate pass decided on — pinned or not, and why. */
export interface PinRecord {
  /** The seed entity the decision is for (spot, card or booking id). */
  entity: string;
  name: string;
  native?: string;
  kind: PinKind;
  /** Pinned? `lat`/`lng` are present exactly when it is. */
  ok: boolean;
  lat?: number;
  lng?: number;
  /** The OSM answer the verdict is about — the pin, or the reason's subject. */
  osm?: string;
  /** That answer's own name. */
  matched?: string;
  /** Its class=type. */
  osmClass?: string;
  /** Great-circle km from the anchor, and the limit it was held to. */
  km?: number;
  anchor: Coord;
  nearKm: number;
  sources?: PinSources;
  /** The Wikidata item that agreed, and how far from the OSM answer. */
  wd?: string;
  wdKm?: number;
  /** A bed's OSM street address, to read beside the booked one (the audit). */
  osmAddress?: string;
  reason: string;
}

/** A coordinate the trip already stored (coords.ts), measured against both
    sources. Reported, never changed by the pass. */
export interface CoordCheck {
  entity: string;
  name: string;
  coord: Coord;
  osm?: string;
  matched?: string;
  osmClass?: string;
  /** km from our coordinate to OSM's first answer, and whether its name agreed. */
  osmKm?: number;
  named?: boolean;
  /** OSM's answer carries the name AND our coordinate sits inside it — only
      then do its tags say anything about the place (categories.ts rule 2). */
  osmAgrees?: boolean;
  wd?: string;
  wdName?: string;
  /** km from our coordinate to that Wikidata item's P625. */
  wdKm?: number;
  confirmed: boolean;
  verdict: string;
}

const line = (key: string, v: unknown) => `  ${JSON.stringify(key)}: ${JSON.stringify(v)},`;

export function renderPins(asOf: string, pins: Record<string, PinRecord>, checks: Record<string, CoordCheck>): string {
  const pinned = Object.values(pins).filter((p) => p.ok).length;
  return [
    '/* GENERATED by `PLACES_PINS=1 npm run verify:places` — do not edit by hand.',
    '',
    `   The coordinate pass over OpenStreetMap and Wikidata answers of ${asOf}:`,
    `   ${pinned} of ${Object.keys(pins).length} places pinned under the rules in china/pin-rules.ts, and`,
    `   ${Object.keys(checks).length} coordinates the trip already stored measured against both sources.`,
    '   The seed build (china/transform.ts) reads PINS; nothing here is looked up at',
    '   runtime. To change a decision, change the rules or the trip, and re-run —',
    '   docs/design/horizon/MAP-DATA.md is the audit of this file. */',
    "import type { CoordCheck, PinRecord } from './pins-format';",
    '',
    `export const PINS_AS_OF = ${JSON.stringify(asOf)};`,
    '',
    '/** Every place the pass decided on — pinned or not, and why. */',
    'export const PINS: Record<string, PinRecord> = {',
    ...Object.entries(pins).map(([k, v]) => line(k, v)),
    '};',
    '',
    '/** The coordinates the trip already stored, measured — reported, never changed. */',
    'export const COORD_CHECKS: Record<string, CoordCheck> = {',
    ...Object.entries(checks).map(([k, v]) => line(k, v)),
    '};',
    '',
  ].join('\r\n');
}
